<?php
/**
 * ============================================================
 *  logout.php - ログアウト処理
 * ============================================================
 *
 * 【流れ】
 *   1. session_start() でセッションを使える状態にする
 *   2. $_SESSION = []   … セッション変数を空に
 *   3. session_destroy() … サーバー側のセッションファイル自体を破棄
 *   4. ログイン画面へリダイレクト
 *
 * セッションを完全に消すために 2 と 3 の両方を行うのがポイント。
 */

session_start();

// セッション変数（user_id, csrf_token など）を全削除
$_SESSION = [];

// セッションそのものを破棄
session_destroy();

// ログイン画面へリダイレクト
header('Location: login.php');
exit;
